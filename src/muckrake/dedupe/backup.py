"""Export and import the resolver's judgements, like ner-export and ner-import.

The file is nomenklatura's edge format, one JSON object per line (``.gz`` to
compress). By default only judgements a person made are exported: those by the
automatic processes below can be regenerated by running them again. Suggestions
(no judgement yet) are never exported, since xref recreates them.
"""

import gzip
import json
from collections import defaultdict
from itertools import combinations
from pathlib import Path
from typing import IO

from nomenklatura.judgement import Judgement
from nomenklatura.resolver import Resolver
from nomenklatura.resolver.edge import Edge

# Users that record judgements automatically. Every other user is a person
# (including `muckrake/manual`, which `dedupe-manual` records for a person).
AUTOMATIC_USERS = frozenset({"muckrake/xref", "muckrake/edge-dedupe"})


def _open(path: Path, write: bool) -> IO[str]:
    if path.suffix == ".gz":
        return gzip.open(path, "wt" if write else "rt", encoding="utf-8")
    return path.open("w" if write else "r", encoding="utf-8")


def export_judgements(resolver: Resolver, path: Path, include_automatic: bool = False) -> int:
    """Write the resolver's live judgements to ``path``; returns how many."""
    count = 0
    with _open(path, write=True) as fh:
        for edge in resolver.all_edges():
            if not include_automatic and edge.user in AUTOMATIC_USERS:
                continue
            fh.write(json.dumps(edge.to_dict()) + "\n")
            count += 1
    return count


def import_judgements(resolver: Resolver, path: Path) -> tuple[int, int]:
    """Add judgements from an export; returns (imported, kept).

    An export never overrides a decision made here. A merge in the file (its
    positive edges, which point at a canonical ID) is imported only if none of
    the entities it joins are kept apart here; a negative or unsure judgement
    only if the pair isn't judged here yet. Everything else is kept as it is
    here. A pair with only a suggestion takes the exported judgement.
    """
    edges: list[Edge] = []
    with _open(path, write=False) as fh:
        for line in fh:
            if line.strip():
                edges.append(Edge.from_dict(json.loads(line)))

    # The clusters the file's positive edges would form.
    parent: dict[str, str] = {}

    def find(node: str) -> str:
        parent.setdefault(node, node)
        while parent[node] != node:
            parent[node] = parent[parent[node]]
            node = parent[node]
        return node

    for edge in edges:
        if edge.judgement == Judgement.POSITIVE:
            parent[find(edge.source.id)] = find(edge.target.id)
    clusters: dict[str, set[str]] = defaultdict(set)
    for node in parent:
        clusters[find(node)].add(node)
    blocked = {
        root
        for root, members in clusters.items()
        if any(
            resolver.get_judgement(left, right) not in (Judgement.NO_JUDGEMENT, Judgement.POSITIVE)
            for left, right in combinations(sorted(members), 2)
        )
    }

    accepted: list[Edge] = []
    for edge in edges:
        local = resolver.get_judgement(edge.source.id, edge.target.id)
        if edge.judgement == Judgement.POSITIVE:
            if find(edge.source.id) in blocked or local == Judgement.POSITIVE:
                continue
        elif local != Judgement.NO_JUDGEMENT:
            continue
        accepted.append(edge)
    if accepted:
        resolver.load_edges(accepted)
        # The imported edges keep their original times, which the incremental
        # index update skips, so rebuild it.
        resolver.load_into_memory()
    return len(accepted), len(edges) - len(accepted)
