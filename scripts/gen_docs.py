"""Generate docs/cli.md and docs/env.md from the code.

    uv run python scripts/gen_docs.py

docs/cli.md comes from the click command tree in muckrake.cli, and docs/env.md
from ``muckrake.settings.ENV_VARS``. tests/test_docs_current.py regenerates both
in memory and fails when the committed files differ, so rerun this script after
changing a command, an option or an environment variable.
"""

from pathlib import Path

import click

from muckrake.cli import cli
from muckrake.settings import ENV_VARS

DOCS_PATH = Path(__file__).parent.parent / "docs"
GENERATED = "<!-- Generated by scripts/gen_docs.py; do not edit by hand. -->"
# Fixed help width, so the output doesn't depend on the terminal running the script.
WIDTH = 88


def _help(command: click.Command, name: str, parent: click.Context | None = None) -> str:
    ctx = click.Context(
        command, info_name=name, parent=parent, terminal_width=WIDTH, max_content_width=WIDTH
    )
    return command.get_help(ctx)


def render_cli() -> str:
    root = click.Context(cli, info_name="muckrake", terminal_width=WIDTH)
    lines = [
        GENERATED,
        "",
        "# Command-line reference",
        "",
        "Every `muckrake` command with its arguments and options, as printed by `--help`.",
        "",
        "```text",
        _help(cli, "muckrake"),
        "```",
    ]
    for name in cli.list_commands(root):
        command = cli.get_command(root, name)
        if command is None or command.hidden:
            continue
        lines += ["", f"## `muckrake {name}`", "", "```text", _help(command, name, root), "```"]
    return "\n".join(lines) + "\n"


def render_env() -> str:
    lines = [
        GENERATED,
        "",
        "# Environment variables",
        "",
        "muckrake reads these from the environment, after loading the nearest `.env` "
        "file from the current directory upward (see `MUCKRAKE_ENV_FILE`). "
        "`.env.example` is a commented template.",
        "",
        "| Variable | Default | Purpose |",
        "|---|---|---|",
    ]
    for var in ENV_VARS:
        lines.append(f"| `{var.name}` | {var.default} | {var.description} |")
    return "\n".join(lines) + "\n"


def main() -> None:
    DOCS_PATH.mkdir(exist_ok=True)
    (DOCS_PATH / "cli.md").write_text(render_cli())
    (DOCS_PATH / "env.md").write_text(render_env())


if __name__ == "__main__":
    main()
